def test_setup_appends_to_an_existing_csv(tmp_path):
    shapes = _env(tmp_path, ids=(0, 1))
    other = tmp_path / "other.geojson"
    _shapes(other, [2])
    _setup(tmp_path, shapes)                       # id 0 and 1, window 1
    _setup(tmp_path, other, window=W2)             # id 2, another window
    only0 = tmp_path / "only0.geojson"
    _shapes(only0, [0])
    csv = _setup(tmp_path, only0)                  # id 0 again: duplicates the first row
    _check("setup_existing_csv", _text(csv, tmp_path))


def test_setup_duplicate_ids_refused_before_any_write(tmp_path):
    _make_catalog(tmp_path / "sentinel-2-l2a" / "catalog.parquet", tmp_path)
    shapes = tmp_path / "dupes.geojson"
    _duplicate_id_shapes(shapes)
    before = sorted(os.listdir(tmp_path))
    with pytest.raises(ValueError) as exc:
        _setup(tmp_path, shapes)
    assert sorted(os.listdir(tmp_path)) == before
    assert not (tmp_path / "run").exists()
    _check("setup_duplicate_ids", _norm(exc.value, tmp_path))


def test_setup_no_work_units_leaves_existing_csv_untouched(tmp_path):
    shapes = _env(tmp_path, ids=(0,))
    csv = _setup(tmp_path, shapes)
    with open(csv, "rb") as f:
        before = f.read()
    outside = tmp_path / "outside.geojson"
    _shapes(outside, [7], outside_ids=(7,))
    with pytest.raises(create_datacube.NoWorkUnitsError) as exc:
        _setup(tmp_path, outside)
    with open(csv, "rb") as f:
        assert f.read() == before
    _check("setup_no_work_units", _norm(exc.value, tmp_path))


