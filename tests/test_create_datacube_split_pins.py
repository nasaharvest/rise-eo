def test_walk_call_order(tmp_path, monkeypatch):
    shapes = _env(tmp_path, ids=(0, 1, 2))
    first = tmp_path / "first.geojson"
    _shapes(first, [0, 1])
    _walk(tmp_path, first)                         # rows for 0 and 1; id 2 is the shortfall
    csv_fp = str(tmp_path / "run" / "input.csv")
    events: list = []

    real_open, real_presence = fs.open, create_datacube._presence_for_paths
    real_setup = create_datacube.setup

    def spy_open(path, mode="r", *a, **kw):
        if str(path) == csv_fp:
            events.append(("open", mode))
        return real_open(path, mode, *a, **kw)

    def spy_presence(paths, **kw):
        events.append("presence")
        return real_presence(paths, **kw)

    def spy_print(*args, **kw):
        if args and str(args[0]).startswith("[plan]"):
            events.append("plan")
        print(*args, **kw)

    def spy_setup(**kw):
        events.append("setup")
        return real_setup(**kw)

    monkeypatch.setattr(fs, "open", spy_open)
    monkeypatch.setattr(create_datacube, "_presence_for_paths", spy_presence)
    monkeypatch.setattr(create_datacube, "print", spy_print, raising=False)
    monkeypatch.setattr(create_datacube, "setup", spy_setup)
    result = _walk(tmp_path, shapes)
    _check("walk_call_order", (result, events))


