def _make_catalog(cat_path, tmp_path):
    rows = []
    for i, mgrs in enumerate(["T33UVP", "T33UVP"]):
        tif = tmp_path / f"tile_{i}.tif"
        tif.write_bytes(b"\x00")
        rows.append({
            "id": f"g{i}", "acquisition_key": f"g{i}", "processing_version": None,
            "processing_datetime": None, "source": "mpc",
            "properties": '{"s2:foo": "bar"}',
            "mgrs_tile": mgrs, "timestamp": pd.Timestamp("2018-04-01", tz="UTC"),
            "band": "B04", "filepath": str(tif),
            "geometry": box(0, 0, 10, 10),
        })
    gdf = gpd.GeoDataFrame(rows, crs="EPSG:4326")
    gdf["area_contribution"] = 1.0
    fs.write_parquet(str(cat_path), gdf)


def _shapes(path, ids, *, outside_ids=()):
    """`ids` inside the `_make_catalog` bbox, except any in `outside_ids` (no tile there)."""
    geoms = []
    for i in ids:
        if i in outside_ids:
            geoms.append(box(1000 + i, 1000, 1001 + i, 1001))
        else:
            geoms.append(box(i + 1, i + 1, i + 2, i + 2))
    gpd.GeoDataFrame(
        {"id": list(ids), "label": [f"l{i}" for i in ids], "geometry": geoms}, crs="EPSG:4326",
    ).to_file(path, driver="GeoJSON")


def _duplicate_id_shapes(path):
    gpd.GeoDataFrame(
        {"id": ["a", "a", "b", "b", "b", "c"], "label": list("uvwxyz"),
         "geometry": [box(i, i, i + 1, i + 1) for i in range(6)]}, crs="EPSG:4326",
    ).to_file(path, driver="GeoJSON")


class _PdWithFixedClock:
    """The module's `pd`, except `pd.Timestamp.now` is a counter clock (one minute a call)."""

    def __init__(self):
        self._n = 0
        self.Timestamp = types.SimpleNamespace(now=self._now)

    def _now(self, tz=None):
        self._n += 1
        return pd.Timestamp("2030-01-01", tz="UTC") + pd.Timedelta(minutes=self._n)

    def __getattr__(self, name):
        return getattr(pd, name)


@pytest.fixture(autouse=True)
def _fixed_clock(monkeypatch):
    monkeypatch.setattr(create_datacube, "pd", _PdWithFixedClock())


def _text(path, tmp_path):
    if not os.path.exists(path):
        return None
    with open(path, "rb") as f:
        return f.read().decode().replace(str(tmp_path), "<tmp>")


def _norm(text, tmp_path):
    return str(text).replace(str(tmp_path), "<tmp>")


def _check(name, obs):
    assert obs == EXPECTED[name]


def _setup(tmp_path, shapes, *, window=W1, csv="input.csv", label_col="label", **extra):
    kwargs = dict(
        catalog_filepath=str(tmp_path / "sentinel-2-l2a" / "catalog.parquet"),
        timestamp_col="timestamp", shapefilepath=str(shapes), id_col="id",
        run_folderpath=str(tmp_path / "run"), bands=["B04"], mosaic_days=20,
        csv_filepath=str(tmp_path / "run" / csv), label_col=label_col, **window,
    )
    kwargs.update(extra)
    create_datacube.setup(**kwargs)
    return kwargs["csv_filepath"]


def _walk(tmp_path, shapes, *, window=W1, label_col="label", **extra):
    kwargs = dict(
        catalog_filepath=str(tmp_path / "sentinel-2-l2a" / "catalog.parquet"),
        timestamp_col="timestamp", shapefilepath=str(shapes), id_col="id",
        run_folderpath=str(tmp_path / "run"), bands=["B04"], mosaic_days=20,
        csv_filepath=str(tmp_path / "run" / "input.csv"), label_col=label_col, **window,
    )
    kwargs.update(extra)
    return create_datacube.build_shortfall_only(**kwargs)


def _env(tmp_path, ids=(0, 1), *, outside_ids=()):
    _make_catalog(tmp_path / "sentinel-2-l2a" / "catalog.parquet", tmp_path)
    shapes = tmp_path / "shapes.geojson"
    _shapes(shapes, list(ids), outside_ids=outside_ids)
    return shapes


def _csv(tmp_path):
    return _text(str(tmp_path / "run" / "input.csv"), tmp_path)


def _plan_lines(capsys, tmp_path, *prefixes):
    out = capsys.readouterr().out
    return [_norm(line, tmp_path) for line in out.splitlines() if line.startswith(prefixes)]


def _make_cube(tmp_path, shapes_ids, window=W1, **extra):
    """Write a non-empty cube + metadata where `build_shortfall_only` expects them."""
    decl = create_datacube._collections.get("sentinel-2-l2a")
    segment = create_datacube.window_folder_segment(
        pd.to_datetime(window["startdate"], utc=True), pd.to_datetime(window["enddate"], utc=True),
        20, bands=["B04"], mosaic_scheme=create_datacube.config.MOSAIC_SCHEME,
        collection="sentinel-2-l2a", declaration=decl, **extra)
    for i in shapes_ids:
        folder = create_datacube.cube_export_folderpath(str(tmp_path / "run"), segment, i)
        os.makedirs(folder, exist_ok=True)
        for name in (create_datacube.CUBE_NAME, create_datacube.CUBE_METADATA_NAME):
            with open(os.path.join(folder, name), "wb") as f:
                f.write(b"x")
    return segment


